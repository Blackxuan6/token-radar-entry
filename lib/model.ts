// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every rankable pre-token protocol: the snapshot's watchlist (the floor, never a
// ceiling) plus every pre-token protocol below the floor that is not an exchange and not a versioned
// pool. Live-token protocols are kept apart and shown with the market's own values, never mixed into
// the ranking.
//
// Implied value follows only from the snapshot's own figures, by comparables:
//
//   multiple   = the category's median market-cap-to-TVL ratio among the snapshot's live-token
//                protocols, shrunk toward the global median when the category has few comps,
//                clamped to [0.03, 1.50]; a category with no comps takes the global median.
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -50, 150) per cent
//   growthMult = 1 + (growth / 100) x 0.6
//   maturity   = 0.55 + min(age_days, 1095) / 1095 x 0.45   (age_days unknown: 365)
//   breadth    = 1 + min(max(chains - 1, 0), 9) x 0.02
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the multiples come
// from the snapshot's own live market, not from a hand-kept list.

import farmApi from './farm.js';

/** The farm-plan API the shared lib/farm.js module carries (plain JS, no types of its own). */
interface FarmApi {
  farmStepsFor: (p: SnapshotProtocol, age: number | null) => string[];
}
const { farmStepsFor } = farmApi as unknown as FarmApi;

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  multiple_floor: number;
  multiple_cap: number;
  shrink_k: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_days: 1095,
  unknown_age_days: 365,
  multiple_floor: 0.03,
  multiple_cap: 1.5,
  shrink_k: 8,
  breadth_per_chain: 0.02,
  breadth_max_chains: 9,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

